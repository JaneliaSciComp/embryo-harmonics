"""Webster-Horn approximations of the harmonics of an ovoid.

The plain Webster-Horn equation parametrizes the body by its radius R(z),
which breaks down at round caps: R'(z) -> infinity at the tips. The z-horn
offers three ways to treat the caps; see :func:`compute_horn_z_harmonics`.
The phi-horn parametrizes the body by its polar outline r(phi) around the
centroid instead, which has no singularity at the tips; see
:func:`compute_horn_phi_harmonics`.
"""
import functools
import itertools
import logging

import numpy as np
import pyvista as pv
from scipy.optimize import brentq
from scipy.special import spherical_jn

from embryoharmonics.celegans.ovoid import OvoidModel
from embryoharmonics.celegans.webster_horn_harmonics import (
    _branch_modes,
    _select_modes,
    meridian_harmonics,
)
from embryoharmonics.webster_horn import sturm_liouville


CAP_TREATMENTS = ("natural", "flat", "corrected")

_logger = logging.getLogger(__name__)


def compute_horn_z_harmonics(
        mesh: pv.UnstructuredGrid,
        ovoid: OvoidModel,
        *,
        n: int = 10,
        caps: str = "natural",
        angular_order: int | None = None,
        max_wall_angle: float = 60.0,
        n_samples: int = 400,
) -> tuple["AxisymmetricHarmonics", list[tuple[int, int, int]]]:
    """Approximate the first ``n`` harmonics of an ovoid with the Webster-Horn
    equation in the axial coordinate z, represented on its meridian mesh.

    The caps can be treated in three ways:

    - ``natural``: solve on the whole axis; the weight R^2 vanishes at the
      tips, which takes care of the end conditions.
    - ``flat``: cut the body where the wall gets steeper than
      ``max_wall_angle`` (against the axis) and close it with flat, Neumann
      ends; beyond the cuts the envelopes are continued constantly, with the
      transverse shape still scaled to the true local radius.
    - ``corrected``: like ``natural``, but keep the wall-slope terms that the
      plain equation neglects (see
      :func:`embryoharmonics.webster_horn.webster_envelopes`).

    :param mesh: The meridian triangle mesh with points (r, 0, z), as
        generated by :meth:`OvoidModel.generate_meridian_mesh`
    :param ovoid: The ovoid model providing the radius profile
    :param n: The number of harmonics to approximate; if ``angular_order`` is
        given, the number of modes of that branch
    :param caps: The cap treatment, one of :data:`CAP_TREATMENTS`
    :param angular_order: If given, compute only this azimuthal branch m
        ('cos' only; the degenerate 'sin' partners are not duplicated)
    :param max_wall_angle: The wall angle in degrees at which ``flat`` caps
        cut the body
    :param n_samples: The number of outline points to sample the profile at
        (uniformly in the polar angle, so they cluster at the tips)
    :return: The approximate harmonics on the meridian mesh, and their
        ``(m, l, n)`` mode labels
    """
    if caps not in CAP_TREATMENTS:
        raise ValueError(f"Unknown cap treatment '{caps}', use one of {CAP_TREATMENTS}")

    R, z = ovoid.outline(n_samples)
    R, z = R[::-1], z[::-1]  # ascending z

    s, R_horn = z, R
    if caps == "flat":
        steep = np.abs(np.gradient(R, z)) > np.tan(np.radians(max_wall_angle))
        first, last = np.flatnonzero(~steep)[[0, -1]]
        s, R_horn = z[first:last + 1], R[first:last + 1]
        _logger.info("Flat caps at z = %.1f and z = %.1f", s[0], s[-1])

    corrected = caps == "corrected"
    if angular_order is None:
        candidates = _select_modes(s, R_horn, n, corrected=corrected)
    else:
        candidates = _branch_modes(s, R_horn, n, angular_order, corrected=corrected)

    z_node = mesh.points[:, 2]
    s_node = np.clip(z_node, s[0], s[-1])
    R_node = np.interp(z_node, z, R)
    return meridian_harmonics(mesh, candidates, s, s_node, R_node)


def compute_horn_phi_harmonics(
        mesh: pv.UnstructuredGrid,
        ovoid: OvoidModel,
        *,
        n: int = 10,
        angular_order: int | None = None,
        n_samples: int = 300,
) -> tuple["AxisymmetricHarmonics", list[tuple[int, int, int]]]:
    """Approximate the first ``n`` harmonics of an ovoid with a horn equation
    in the polar angle phi around the ovoid's center, represented on its
    meridian mesh.

    In spherical coordinates (rho, phi, theta), every mode is approximated as

        u = A(phi) * j_k(kappa_{k,p} * rho / r(phi)) * cos/sin(m * theta),

    i.e. at every polar angle the radial shape is the k-th order radial mode
    of a ball of the local radius r(phi), with kappa_{k,p} the p-th zero of
    j_k'. Integrating the Rayleigh quotient over rho gives a 1D problem for
    the envelope A(phi) (see :func:`_horn_phi_mode`), which is exact for a
    ball. There, the envelope of the (k, p, m) mode is the associated Legendre
    function P_k^m, which has k - m nodes; so of the envelopes of a radial
    shape, only the one with k - m nodes is kept.

    :param mesh: The meridian triangle mesh with points (r, 0, z), as
        generated by :meth:`OvoidModel.generate_meridian_mesh`
    :param ovoid: The ovoid model providing the outline r(phi)
    :param n: The number of harmonics to approximate; if ``angular_order`` is
        given, the number of modes of that branch
    :param angular_order: If given, compute only this azimuthal branch m
        ('cos' only; the degenerate 'sin' partners are not duplicated)
    :param n_samples: The number of grid points in phi
    :return: The approximate harmonics on the meridian mesh, and their
        ``(m, k, p)`` mode labels (azimuthal order, order of the radial
        shape, radial zero)
    """
    from embryoharmonics.celegans.axisymmetric import AxisymmetricHarmonics

    phi = np.linspace(0, np.pi, n_samples)
    multiplicity = 1 if angular_order is not None else 2

    # Every branch's eigenvalues grow with k and p (and its lowest one with
    # m), so each loop stops at the first mode above the cutoff; it starts as
    # a generous estimate and shrinks to the n-th eigenvalue found so far
    estimate = 2 * _weyl_eigenvalue(ovoid, n if angular_order is None else n * n)
    while True:
        modes = _horn_phi_modes(ovoid, phi, n, angular_order, estimate)
        if sum(1 if c["m"] == 0 else multiplicity for c in modes) >= n:
            break
        estimate *= 2

    # Expand m > 0 modes into cos/sin pairs, never splitting a pair
    selected = []
    for mode in modes:
        trigs = ("cos", "sin") if mode["m"] > 0 and angular_order is None else ("cos",)
        selected.extend({**mode, "trig": trig} for trig in trigs)
        if len(selected) >= n:
            break

    rho = np.hypot(mesh.points[:, 0], mesh.points[:, 2])
    phi_node = np.arctan2(mesh.points[:, 0], mesh.points[:, 2])
    xi = rho / ovoid.radius(phi_node)
    fields = np.array([
        np.interp(phi_node, phi, c["envelope"]) * _radial_shape(c["k"], c["kappa"], xi)
        for c in selected
    ])

    harmonics = AxisymmetricHarmonics(
        mesh,
        fields,
        np.array([c["eigenvalue"] for c in selected]),
        np.array([c["m"] for c in selected]),
        np.array([c["trig"] for c in selected]),
    )
    return harmonics, [(c["m"], c["k"], c["p"]) for c in selected]


def _horn_phi_modes(
        ovoid: OvoidModel,
        phi: np.ndarray,
        n: int,
        angular_order: int | None,
        cutoff: float,
) -> list[dict]:
    """All phi-horn modes below the cutoff, which shrinks to the n-th
    eigenvalue (counting cos/sin pairs twice unless ``angular_order`` is
    given) once that many modes are found; sorted by eigenvalue.
    """
    multiplicity = 1 if angular_order is not None else 2
    modes = []
    orders = [angular_order] if angular_order is not None else itertools.count()
    for m in orders:
        for k in itertools.count(m):
            for p in itertools.count(1):
                mode = _horn_phi_mode(ovoid, phi, m, k, p)
                if mode["eigenvalue"] > cutoff:
                    break
                modes.append(mode)
                modes.sort(key=lambda c: c["eigenvalue"])
                counts = np.cumsum([1 if c["m"] == 0 else multiplicity for c in modes])
                if counts[-1] >= n:
                    cutoff = min(cutoff, modes[np.searchsorted(counts, n)]["eigenvalue"])
            if p == 1:
                break
        if k == m:
            break
    return modes


def _weyl_eigenvalue(ovoid: OvoidModel, n: int) -> float:
    """Estimate the n-th Neumann eigenvalue of the ovoid from the two-term
    Weyl law N(lambda) = V lambda^(3/2) / (6 pi^2) + S lambda / (16 pi).
    """
    phi = np.linspace(0, np.pi, 1001)
    r, dr = ovoid.radius(phi), ovoid.radius(phi, derivative=True)
    volume = 2 * np.pi / 3 * np.trapezoid(r ** 3 * np.sin(phi), phi)
    surface = 2 * np.pi * np.trapezoid(r * np.sin(phi) * np.hypot(r, dr), phi)
    count = lambda lam: volume * lam ** 1.5 / (6 * np.pi ** 2) + surface * lam / (16 * np.pi)
    return brentq(lambda lam: count(lam) - n, 0, 1e3 * n / volume ** (2 / 3))


@functools.lru_cache(maxsize=None)
def sph_jp_zero(k: int, p: int) -> float:
    """Return the p-th (1-indexed) zero of j_k', the derivative of the k-th
    order spherical Bessel function of the first kind; for k = 0 the first
    zero is the trivial one at 0 (constant radial shape).

    :param k: The order of the spherical Bessel function
    :param p: The 1-indexed zero to return
    :return: kappa_{k,p}
    """
    if k == 0 and p == 1:
        return 0.0

    derivative = lambda x: spherical_jn(k, x, derivative=True)
    zeros = []
    # Zeros of j_k' are spaced by about pi; the first one is above k
    grid = np.arange(max(k, 0.5), k + (p + 2) * np.pi, 0.05)
    values = derivative(grid)
    for i in np.flatnonzero(np.sign(values[:-1]) != np.sign(values[1:])):
        zeros.append(brentq(derivative, grid[i], grid[i + 1]))
    return zeros[p - 1 if k > 0 else p - 2]


def _radial_shape(k: int, kappa: float, xi: np.ndarray) -> np.ndarray:
    """The radial shape j_k(kappa * xi) of a phi-horn mode."""
    return spherical_jn(k, kappa * xi) if kappa > 0 else np.ones_like(xi)


@functools.lru_cache(maxsize=None)
def _radial_integrals(k: int, p: int) -> tuple[float, float, float, float]:
    """The integrals over 0 <= xi <= 1 of the radial shape g(xi) =
    j_k(kappa_{k,p} * xi) that enter the phi-horn equation:

        I1 = int g'^2 xi^2,  I2 = int g^2,  I3 = int g^2 xi^2,
        J1 = int g g' xi = g(1)^2 / 2 - I2 / 2.
    """
    kappa = sph_jp_zero(k, p)
    # Gauss-Legendre on [0, 1], enough points for the p - 1 oscillations
    nodes, weights = np.polynomial.legendre.leggauss(64 + 4 * (k + p))
    xi, weights = (nodes + 1) / 2, weights / 2
    g = _radial_shape(k, kappa, xi)
    dg = kappa * spherical_jn(k, kappa * xi, derivative=True)

    I1 = weights @ (dg ** 2 * xi ** 2)
    I2 = weights @ g ** 2
    I3 = weights @ (g ** 2 * xi ** 2)
    J1 = _radial_shape(k, kappa, np.array(1.0)) ** 2 / 2 - I2 / 2
    return I1, I2, I3, J1


def _horn_phi_mode(ovoid: OvoidModel, phi: np.ndarray, m: int, k: int, p: int) -> dict:
    """Solve the phi-horn equation of the (m, k, p) mode.

    Inserting u = A(phi) g(rho / r(phi)) cos(m theta) with g the radial shape
    into the Rayleigh quotient and integrating over rho (volume element
    rho^2 sin(phi)) gives the energy and mass densities

        sin(phi) [I2 r A'^2 - 2 J1 r' A A' + I1 (r + r'^2 / r) A^2
                  + m^2 I2 r A^2 / sin(phi)^2],
        sin(phi) I3 r^3 A^2

    (integrals from :func:`_radial_integrals`). For a ball (r' = 0) the
    envelopes are associated Legendre functions P_L^m, with eigenvalues
    (I1 + L (L + 1) I2) / (I3 r^2), which is exact, (kappa_{k,p} / r)^2, for
    L = k. For m > 0 the m^2 / sin(phi) potential forces A = 0 at the poles.
    """
    I1, I2, I3, J1 = _radial_integrals(k, p)
    mid = (phi[:-1] + phi[1:]) / 2
    sin = np.sin(mid)
    r = ovoid.radius(mid)
    dr = ovoid.radius(mid, derivative=True)

    stiffness = I2 * r * sin / I3
    coupling = -J1 * dr * sin / I3
    potential = sin * (I1 * (r + dr ** 2 / r) + m ** 2 * I2 * r / sin ** 2) / I3
    weight = r ** 3 * sin

    index = k - m
    eigenvalues, envelopes = sturm_liouville(
        phi, stiffness, potential, weight, coupling,
        fixed_ends=m > 0, subset=(index, index),
    )
    return {
        "eigenvalue": eigenvalues[0],
        "m": m,
        "k": k,
        "p": p,
        "kappa": sph_jp_zero(k, p),
        "envelope": envelopes[:, 0],
    }
